function ns.AddTranslations(lang, t)
    L[lang] = L[lang] or {}
    for k, v in pairs(t) do L[lang][k] = v end
end
local CLIENT_MAP = { enGB = "enUS", esMX = "esES", zhTW = "zhCN", ptBR = "enUS", itIT = "enUS" }
function ns.ActiveLang()
    local l = ns.db and ns.db.global.lang or "auto"
    if l == "auto" then
        l = (GetLocale and GetLocale()) or "enUS"
        l = CLIENT_MAP[l] or l
    end
    if l ~= "enUS" and not L[l] then l = "enUS" end
    return l
end
function ns.T(key)
    local t = L[ns.ActiveLang()]
    return (t and t[key]) or key
end
function ns.LangFont()
    return ns.LANG_FONTS[ns.ActiveLang()]
end
